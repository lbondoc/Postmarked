    private val lat = 37 + 46 / 60.0 + 12.3 / 3600
    private val lng = -(122 + 25 / 60.0 + 9.8 / 3600)

    @Test
    fun readsDateOffsetAndGpsInIntelByteOrder() = assertFullInfo(readExif(GPS_LITTLE_ENDIAN))

    @Test
    fun readsDateOffsetAndGpsInMotorolaByteOrder() = assertFullInfo(readExif(GPS_BIG_ENDIAN))

    @Test
    fun aPhotoWithoutGpsStillHasItsDate() {
        val info = readExif(NO_GPS)
        assertEquals("2026:10:03 14:22:01", info.dateTimeOriginal)
        assertEquals("-07:00", info.offsetTimeOriginal)
        assertNull(info.gps)
    }

    @Test
    fun aTruncatedFileNeverThrowsAndNeverGivesAWrongValue() {
        // Every possible cut, from nothing to one byte short. Each field is either what the whole file says, or null.
        for (cut in 0 until GPS_BIG_ENDIAN.size) {
            val info = readExif(GPS_BIG_ENDIAN.copyOf(cut))
            info.dateTimeOriginal?.let { assertEquals("2026:10:03 14:22:01", it, "cut at $cut") }
            info.offsetTimeOriginal?.let { assertEquals("-07:00", it, "cut at $cut") }
            info.gps?.let { assertTrue(abs(it.lat - lat) < 1e-9 && abs(it.lng - lng) < 1e-9, "cut at $cut: $it") }
        }
        // Cut inside the EXIF block (it starts at byte 24): nothing past the cut can be read.
        assertEquals(ExifInfo(), readExif(GPS_BIG_ENDIAN.copyOf(60)))
    }

    @Test
    fun somethingThatIsNotAJpegGivesNothing() {
        assertEquals(ExifInfo(), readExif(ByteArray(0)))
        assertEquals(ExifInfo(), readExif("not a picture at all".encodeToByteArray()))
        // A HEIC file starts with an ISO box, not a JPEG marker.
        assertEquals(ExifInfo(), readExif(hex("0000001c6674797068656963000000006d696631686569636d696166")))
    }

    @Test
    fun parsesTheExifClockTime() {
        assertEquals(LocalDateTime(2026, 10, 3, 14, 22, 1), exifDateTime("2026:10:03 14:22:01"))
        assertNull(exifDateTime("0000:00:00 00:00:00")) // what cameras write when the clock was never set
        assertNull(exifDateTime(null))
    }

    private fun assertFullInfo(info: ExifInfo) {
        assertEquals("2026:10:03 14:22:01", info.dateTimeOriginal)
        assertEquals("-07:00", info.offsetTimeOriginal)
        val gps = info.gps!!
        assertEquals(lat, gps.lat, 1e-9)
        assertEquals(lng, gps.lng, 1e-9)
    }

    private fun hex(s: String) = ByteArray(s.length / 2) { s.substring(it * 2, it * 2 + 2).toInt(16).toByte() }
